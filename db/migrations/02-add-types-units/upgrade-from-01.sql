-- Скрипт для миграции с прошлой версии базы данных

-- Осталось прежним:
-- equipment_types

-- Переименовал:
-- ranks -> military_ranks
-- users -> employees

-- Новые таблицы:
-- parameter_types - типы измерений, то есть возможные параметры для измерений
-- units - единицы измерения
-- measurements_bucket - соединяет измерения в пачки
-- unit_conversions - таблица для перевода одной единицы измерения в другую

-- Обновил структуру:
-- parameters - теперь хранит единичный параметр, а не измерения всех параметров
-- measurements - теперь хранит единичное измерение, а не ссылку на измерения всех параметров

BEGIN;

-- Простые переименования
ALTER TABLE ranks RENAME TO military_ranks;
ALTER TABLE users RENAME TO employees;

-- Изменение типов колонок на VARCHAR
ALTER TABLE military_ranks ALTER COLUMN title TYPE VARCHAR(100);
ALTER TABLE employees ALTER COLUMN "name" TYPE VARCHAR(100);
ALTER TABLE employees ALTER COLUMN surname TYPE VARCHAR(100);
ALTER TABLE equipment_types ALTER COLUMN title TYPE VARCHAR(100);
ALTER TABLE equipment_types ALTER COLUMN abbreviation TYPE VARCHAR(20);

-- Создание новых таблиц
-- Типы параметров, возможные параметры без единиц измерения
CREATE TABLE parameter_types (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100) UNIQUE NOT NULL
); 
-- Единицы измерения
CREATE TABLE units (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(100) UNIQUE NOT NULL,
    abbreviation VARCHAR(20) NOT NULL UNIQUE
);
-- Пачки измерений
CREATE TABLE measurements_buckets (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INT NOT NULL
);
-- Таблица для перевода единиц измерения
CREATE TABLE unit_conversions (
    from_unit_id INT NOT NULL,
    to_unit_id INT NOT NULL,
    from_value DECIMAL(10, 0),
    to_value DECIMAL(10, 0),
    PRIMARY KEY (from_unit_id, to_unit_id)
);

-- Создание временных таблиц для переноса данных
-- Параметры с единицами измерения, не хранит измерения. То есть связка параметров и единиц измерения
CREATE TABLE temp_parameters (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parameter_type_id INT NOT NULL,
    unit_id INT NOT NULL,
    default_value DECIMAL(10, 0) NULL,
    min_value DECIMAL(10, 0) NULL,
    max_value DECIMAL(10, 0) NULL
);
-- Измерения
CREATE TABLE temp_measurements (
    measurements_bucket_id INT NOT NULL,
    equipment_type_id INT NOT NULL, -- Можно перенести в параметры, чтобы уточнять в них оборудование, которое нужно для измерения
    parameter_id INT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, -- Возможно, стоит перенести в пачки измерений, потому что в приложении не подразумеваются отдельные измерения
    "value" DECIMAL(10, 0) NOT NULL,
    PRIMARY KEY (measurements_bucket_id, parameter_id) -- Гарантирует, что в пачке только одно измерение одного параметра
);

-- Перенос данных из старых таблиц
-- Типы параметров из прошлых таблиц
INSERT INTO parameter_types (title) 
